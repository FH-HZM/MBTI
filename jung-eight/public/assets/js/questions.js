// 交错排列，避免连续同类题目造成作答惯性
function interleave(groups) {
  const order = ['Ne', 'Ni', 'Se', 'Si', 'Te', 'Ti', 'Fe', 'Fi'];
  const buckets = order.map((fn) => groups[fn].map((item) => ({ ...item, fn })));
  const out = [];
  let added = true;
  let round = 0;
  while (added) {
    added = false;
    for (const bucket of buckets) {
      if (bucket[round]) {
        out.push(bucket[round]);
        added = true;
      }
    }
    round += 1;
  }
  return out;
}

