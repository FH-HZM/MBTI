// 交错排列（Ne, Ni, Se, Si, Te, Ti, Fe, Fi 轮流），避免连续同类题目造成作答惯性。
// 交错只影响呈现顺序，不影响计分：每题独立计入所属功能，互不影响。
function interleave(groups) {
  const buckets = FUNCTION_ORDER.map((fn) =>
    groups[fn].map((text, i) => ({ id: `${fn}${i + 1}`, text, fn }))
  );
  const out = [];
  for (let round = 0; round < 10; round += 1) {
    for (const bucket of buckets) out.push(bucket[round]);
  }
  return out;
}

